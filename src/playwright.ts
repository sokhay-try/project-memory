import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import type { MemoryConfig } from './config.js';

/** Find the Playwright CLI installed in the user's project. */
export function resolvePlaywrightCli(root: string): string | null {
  const require = createRequire(path.join(root, 'package.json'));
  for (const id of ['@playwright/test/cli', 'playwright/cli']) {
    try {
      return require.resolve(id);
    } catch {
      // try next
    }
  }
  return null;
}

interface PlaywrightConfigInput {
  workDir: string;
  featureDir: string;
  specFile: string;
  config: MemoryConfig;
}

/** Write a throwaway Playwright config for this one feature test. */
export function writePlaywrightConfig({ workDir, featureDir, specFile, config }: PlaywrightConfigInput): string {
  const pwConfig = {
    testDir: featureDir,
    testMatch: path.basename(specFile),
    outputDir: path.join(workDir, 'test-results'),
    timeout: 120_000,
    workers: 1,
    retries: 0,
    reporter: 'list',
    use: {
      baseURL: config.baseUrl,
      actionTimeout: 15_000,
      viewport: { width: 1280, height: 720 },
      ...(config.slowMo > 0 ? { launchOptions: { slowMo: config.slowMo } } : {}),
    },
    ...(config.startCommand
      ? {
          webServer: {
            command: config.startCommand,
            url: config.baseUrl,
            reuseExistingServer: true,
            timeout: 120_000,
          },
        }
      : {}),
  };

  fs.mkdirSync(workDir, { recursive: true });
  const file = path.join(workDir, 'playwright.config.mjs');
  fs.writeFileSync(
    file,
    `// Generated by project-memory — overwritten on every run.\nexport default ${JSON.stringify(pwConfig, null, 2)};\n`,
  );
  return file;
}

export type RunMode = 'ui' | 'headed' | 'headless';

export function runPlaywright(
  cli: string,
  configFile: string,
  mode: RunMode,
  env: Record<string, string>,
  cwd: string,
): Promise<number> {
  const args = [cli, 'test', '--config', configFile];
  if (mode === 'ui') args.push('--ui');
  if (mode === 'headed') args.push('--headed');

  return new Promise((resolve) => {
    const child = spawn(process.execPath, args, {
      cwd,
      stdio: 'inherit',
      env: { ...process.env, ...env },
    });
    child.on('error', () => resolve(1));
    child.on('close', (code) => resolve(code ?? 1));
  });
}

