import fs from 'node:fs';
import path from 'node:path';
import { toTitle } from './feature.js';

export interface StepRecord {
  index: number;
  title: string;
  status: 'passed' | 'failed';
  durationMs: number;
  error?: string;
}

export interface ApiRecord {
  step: number | null;
  method: string;
  path: string;
  query: string;
  status: number;
  startedMs: number;
  durationMs: number;
  request?: unknown;
  response?: unknown;
  error?: string;
}

export interface RunFile {
  title: string;
  status: string;
  error?: string;
  startedAt: string;
  durationMs: number;
  steps: StepRecord[];
  apis: ApiRecord[];
  video: string | null;
}

export function readRun(file: string): RunFile | null {
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8')) as RunFile;
  } catch {
    return null;
  }
}

const secs = (ms: number) => `${(ms / 1000).toFixed(1)}s`;
const icon = (passed: boolean) => (passed ? '✅' : '❌');
const statusText = (status: number, error?: string) => (status === 0 ? `failed (${error ?? 'network error'})` : String(status));

function stepLabel(run: RunFile, index: number | null): string {
  if (index == null) return 'before first step';
  const s = run.steps.find((x) => x.index === index);
  return s ? `${s.index}. ${s.title}` : `step ${index}`;
}

function json(value: unknown, maxLines = 60): string {
  const lines = JSON.stringify(value, null, 2).split('\n');
  const cut = lines.length > maxLines ? [...lines.slice(0, maxLines), '  …'] : lines;
  return '```json\n' + cut.join('\n') + '\n```';
}

interface DocsInput {
  dir: string;
  name: string;
  entry: string;
  specFile: string;
  run: RunFile;
}

function header(title: string, input: DocsInput, hasVideo: boolean): string[] {
  const { run, entry } = input;
  const date = new Date(run.startedAt).toLocaleString();
  const result = run.status === 'passed' ? '✅ passed' : `❌ ${run.status}`;
  return [
    `# ${toTitle(input.name)} — ${title}`,
    '',
    `> Generated by project-memory · Entry: \`${entry}\` · Last run: ${date} · ${result} · ${secs(run.durationMs)}`,
    ...(hasVideo ? ['', '🎥 [Watch the recording](video.webm)'] : []),
    '',
  ];
}

export function writeFlow(input: DocsInput, hasVideo: boolean): string {
  const { run } = input;
  const out = header('User Flow', input, hasVideo);

  out.push('## Steps', '');
  if (!run.steps.length) out.push('_No steps were recorded._', '');

  for (const s of run.steps) {
    out.push(`${s.index}. ${icon(s.status === 'passed')} **${s.title}** · ${secs(s.durationMs)}`);
    for (const api of run.apis.filter((a) => a.step === s.index)) {
      out.push(`   - \`${api.method} ${api.path}${api.query}\` → ${statusText(api.status, api.error)}`);
    }
    if (s.error) out.push(`   - ⚠️ ${s.error}`);
  }
  out.push('');

  const before = run.apis.filter((a) => a.step == null);
  if (before.length) {
    out.push('## API calls before the first step', '');
    for (const api of before) out.push(`- \`${api.method} ${api.path}${api.query}\` → ${statusText(api.status, api.error)}`);
    out.push('');
  }

  if (run.status !== 'passed' && run.error) {
    out.push('## Why the run failed', '', '```', run.error, '```', '');
  }

  out.push(`Test: [\`${path.basename(input.specFile)}\`](${path.basename(input.specFile)})`, '');

  const file = path.join(input.dir, 'flow.md');
  fs.writeFileSync(file, out.join('\n'));
  return file;
}

export function writeApi(input: DocsInput): string {
  const { run } = input;
  const out = header('APIs', input, false);
  out.push(
    'API calls the frontend made during the recorded flow. Sensitive fields are masked (`***`); long lists are cut to 3 items.',
    '',
  );

  if (!run.apis.length) {
    out.push('_No API calls were recorded. Check `apiPrefix` in project-memory.config.ts._', '');
    fs.writeFileSync(path.join(input.dir, 'api.md'), out.join('\n'));
    return path.join(input.dir, 'api.md');
  }

  // One section per METHOD + path; keep the first call as the example.
  const groups = new Map<string, ApiRecord[]>();
  for (const api of run.apis) {
    const key = `${api.method} ${api.path}`;
    groups.set(key, [...(groups.get(key) ?? []), api]);
  }

  out.push('| Method | Path | Status | Called in step |', '|---|---|---|---|');
  for (const [, calls] of groups) {
    const a = calls[0];
    const statuses = [...new Set(calls.map((c) => statusText(c.status, c.error)))].join(', ');
    const stepsUsed = [...new Set(calls.map((c) => stepLabel(run, c.step)))].join('<br>');
    out.push(`| ${a.method} | \`${a.path}\` | ${statuses} | ${stepsUsed} |`);
  }
  out.push('');

  for (const [key, calls] of groups) {
    const a = calls[0];
    out.push('---', '', `## ${key}`, '');
    out.push(`**Called in:** ${[...new Set(calls.map((c) => stepLabel(run, c.step)))].join(', ')}  `);
    out.push(`**Status:** ${statusText(a.status, a.error)} · ${a.durationMs} ms${calls.length > 1 ? ` · called ${calls.length}×` : ''}`, '');
    if (a.query) out.push(`**Query:** \`${a.query}\``, '');
    if (a.request !== undefined) out.push('**Request body**', '', json(a.request), '');
    if (a.response !== undefined) out.push(`**Response ${a.status}**`, '', json(a.response), '');
  }

  const file = path.join(input.dir, 'api.md');
  fs.writeFileSync(file, out.join('\n'));
  return file;
}

export function writeFeatureJson(input: DocsInput): string {
  const file = path.join(input.dir, 'feature.json');
  fs.writeFileSync(
    file,
    JSON.stringify(
      {
        name: input.name,
        entry: input.entry,
        test: path.basename(input.specFile),
        lastRun: {
          at: input.run.startedAt,
          status: input.run.status,
          durationMs: input.run.durationMs,
          steps: input.run.steps.length,
          apis: input.run.apis.length,
        },
      },
      null,
      2,
    ) + '\n',
  );
  return file;
}
